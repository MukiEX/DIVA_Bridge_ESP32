#!/usr/bin/env python3
"""Pack web/index.html into src/WebPage.h (gzipped byte array) for the
on-device web page. Run after editing web/index.html:

    python3 tools/gen_webpage.py
"""
import argparse, gzip, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(ROOT, "web", "index.html")
dst = os.path.join(ROOT, "src", "WebPage.h")
ap = argparse.ArgumentParser()
ap.add_argument("--html", help="also write the expanded page here (for tests)")
args = ap.parse_args()
html = open(src, encoding="utf-8").read()
html = html.replace("/*BGIMAGE_JS*/", open(os.path.join(ROOT, "web", "bgimage.js"), encoding="utf-8").read())
if args.html:
    open(args.html, "w", encoding="utf-8").write(html)
data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
with open(dst, "w") as f:
    f.write("// Generated by tools/gen_webpage.py from web/index.html - do not edit.\n")
    f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write(f"static const size_t WEB_PAGE_GZ_LEN = {len(data)};\n")
    f.write("static const uint8_t WEB_PAGE_GZ[] = {\n  " + ",\n  ".join(lines) + "\n};\n")
print(f"{dst}: {len(data)} bytes gzipped (from {len(html)})")
